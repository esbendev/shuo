#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "../../..");
const swFilePath = path.join(repoRoot, "sw.js");
const swipeDir = path.join(repoRoot, "other/experimentos/swipe");
const swipeDailyNewsDir = path.join(swipeDir, "daily-news");
const voiceGenDailyNewsDir = path.join(repoRoot, "other/experimentos/voiceGen/audioFiles/daily-news");
const cacQuestionsDir = path.join(repoRoot, "contenido/preguntas/cac");

const SWIPE_BLOCK_START = "    // swipe-cache:start (generated by other/experimentos/swipe/update-sw-cache.js)";
const SWIPE_BLOCK_END = "    // swipe-cache:end";

function toPosix(filePath) {
    return filePath.split(path.sep).join("/");
}

function toProjectUrl(filePath) {
    const relative = toPosix(path.relative(repoRoot, filePath));
    return `/shuo/${relative}`;
}

function listFilesRecursive(dirPath, predicate) {
    if (!fs.existsSync(dirPath)) {
        return [];
    }

    const results = [];
    const stack = [dirPath];

    while (stack.length) {
        const current = stack.pop();
        const entries = fs.readdirSync(current, { withFileTypes: true });
        for (const entry of entries) {
            const absolute = path.join(current, entry.name);
            if (entry.isDirectory()) {
                stack.push(absolute);
                continue;
            }
            if (!predicate || predicate(absolute)) {
                results.push(absolute);
            }
        }
    }

    results.sort((a, b) => toPosix(path.relative(repoRoot, a)).localeCompare(toPosix(path.relative(repoRoot, b))));
    return results;
}

function buildSwipeEntries() {
    const swipeStaticFiles = listFilesRecursive(swipeDir, (filePath) => {
        const relative = toPosix(path.relative(swipeDir, filePath));
        if (relative.startsWith("daily-news/")) {
            return false;
        }
        if (relative === "update-sw-cache.js") {
            return false;
        }
        return relative.endsWith(".html") || (relative.endsWith(".js") && !relative.endsWith(".test.js"));
    }).map(toProjectUrl);

    const swipeDailyNewsJson = listFilesRecursive(swipeDailyNewsDir, (filePath) => filePath.endsWith(".json"))
        .map(toProjectUrl);

    const voiceGenManifests = listFilesRecursive(voiceGenDailyNewsDir, (filePath) => path.basename(filePath) === "manifest.json")
        .map(toProjectUrl);

    const cacQuestionSets = listFilesRecursive(cacQuestionsDir, (filePath) => filePath.endsWith(".json"))
        .map(toProjectUrl);

    return {
        swipeStaticFiles,
        swipeDailyNewsJson,
        voiceGenManifests,
        cacQuestionSets,
    };
}

function renderSwipeBlock(entries) {
    const lines = [SWIPE_BLOCK_START];

    const appendGroup = (label, urls) => {
        lines.push(`    // ${label}`);
        for (const url of urls) {
            lines.push(`    "${url}",`);
        }
    };

    appendGroup("swipe static pages/scripts", entries.swipeStaticFiles);
    appendGroup("swipe daily-news json", entries.swipeDailyNewsJson);
    appendGroup("voiceGen daily-news manifests", entries.voiceGenManifests);
    appendGroup("cac question sets", entries.cacQuestionSets);
    lines.push(SWIPE_BLOCK_END);

    return lines.join("\n");
}

function bumpCacheName(sourceText) {
    const cacheNamePattern = /const CACHE_NAME = "esbendev-shuo-v(\d{6})-(\d+)";/;
    const match = sourceText.match(cacheNamePattern);
    if (!match) {
        throw new Error("Could not parse CACHE_NAME in sw.js");
    }

    const now = new Date();
    const yy = String(now.getFullYear()).slice(-2);
    const mm = String(now.getMonth() + 1).padStart(2, "0");
    const dd = String(now.getDate()).padStart(2, "0");
    const todayToken = `${yy}${mm}${dd}`;

    const currentDateToken = match[1];
    const currentRevision = Number.parseInt(match[2], 10);
    const nextRevision = currentDateToken === todayToken ? currentRevision + 1 : 1;
    const nextCacheName = `esbendev-shuo-v${todayToken}-${nextRevision}`;

    return sourceText.replace(cacheNamePattern, `const CACHE_NAME = "${nextCacheName}";`);
}

function updateServiceWorker() {
    const originalText = fs.readFileSync(swFilePath, "utf8");
    const entries = buildSwipeEntries();
    const generatedBlock = renderSwipeBlock(entries);

    const blockPattern = / {4}\/\/ swipe-cache:start \(generated by other\/experimentos\/swipe\/update-sw-cache\.js\)[\s\S]*? {4}\/\/ swipe-cache:end/;
    if (!blockPattern.test(originalText)) {
        throw new Error("Could not find swipe cache block markers in sw.js");
    }

    let updatedText = originalText.replace(blockPattern, generatedBlock);
    updatedText = bumpCacheName(updatedText);

    fs.writeFileSync(swFilePath, updatedText, "utf8");

    console.log("Updated swipe cache block in sw.js");
    console.log(`- swipe static files: ${entries.swipeStaticFiles.length}`);
    console.log(`- swipe daily-news json: ${entries.swipeDailyNewsJson.length}`);
    console.log(`- voiceGen manifests: ${entries.voiceGenManifests.length}`);
    console.log(`- cac question sets: ${entries.cacQuestionSets.length}`);
}

updateServiceWorker();
